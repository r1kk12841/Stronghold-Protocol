import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'native-dist');
const backendOrigin = process.env.SP_BACKEND_ORIGIN || 'https://stronghold-protocol-a4ul.onrender.com';
const contentOrigin = process.env.SP_CONTENT_ORIGIN || null;

await fs.rm(out, { recursive: true, force: true });
await fs.mkdir(out, { recursive: true });

const publicRoot = path.join(root, 'public');
const omitted = [path.join(publicRoot, 'assets'), path.join(publicRoot, 'fonts')];
await fs.cp(publicRoot, out, {
  recursive: true,
  filter: (source) => !omitted.some((dir) => source === dir || source.startsWith(dir + path.sep)),
});

for (const [from, to] of [
  ['data', 'data'],
  ['shared', 'shared'],
  ['server/match', 'match'],
  ['server/sim', 'sim'],
]) {
  await fs.cp(path.join(root, from), path.join(out, to), { recursive: true });
}

const runtime = `// Generated by tools/build-native-client.mjs\n` +
  `globalThis.__SP_RUNTIME_CONFIG__ = Object.freeze(${JSON.stringify({ backendOrigin, contentOrigin, assetSourceMap: '/data/asset-sources.map', native: true })});\n`;
await fs.writeFile(path.join(out, 'runtime-config.js'), runtime, 'utf8');

// Native uses system fallbacks instead of downloading the optional font pack.
const indexPath = path.join(out, 'index.html');
const index = await fs.readFile(indexPath, 'utf8');
await fs.writeFile(indexPath, index.replace(/^\s*<link rel="stylesheet" href="\/fonts\/fonts\.css" \/>\s*$/m, ''), 'utf8');

console.log(`[native] local client built in ${out}`);
console.log(`[native] co-op backend: ${backendOrigin}`);
console.log(`[native] streamed assets: ${contentOrigin || 'upstream repositories from data/asset-sources.map'}`);
